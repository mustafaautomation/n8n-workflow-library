def _setup(workflow_id: str, extras: list[str] | None = None) -> list[str]:
    steps = [
        "Import `workflow.json` with n8n's Import from File. The workflow arrives inactive.",
        "Select **Run demo** and execute it. **Package demo result** returns `status: demo_ready` plus the summary, route, record, and actions.",
        "Create each credential listed below in n8n and choose it on the matching node. The `PLACEHOLDER_*` ids are labels, not secrets.",
        "Replace every `YOUR_*` resource id (sheet, channel, list, parent page, calendar) with a resource you own.",
        f"Optional HTTP check: POST `sample-input.json` to `/webhook/{workflow_id}` while the workflow is published. The default `demo: true` flag stays on the offline path.",
        "Connect the live apps, send the same JSON with `\"demo\": false`, confirm one real record, then publish.",
    ]
    if extras:
        steps.extend(extras)
    return steps


def _tips(category: str, specific: list[str]) -> list[str]:
    return specific + CATEGORY_TIPS[category]


def _wf(**kwargs):
    logic_kind = kwargs.pop("logic")
    logic_cfg = kwargs.pop("logic_cfg", {})
    kwargs["logic_js"] = GENERATORS[logic_kind](logic_cfg)
    kwargs.setdefault("difficulty", "intermediate")
    kwargs.setdefault("pattern", "linear")
    kwargs.setdefault("polished", False)
    kwargs.setdefault("triggers", [])
    kwargs["setup"] = _setup(kwargs["id"], kwargs.pop("setup_extra", None))
    kwargs["tips"] = _tips(kwargs["category"], kwargs["tips"])
    return kwargs


